#!/usr/bin/env node
/**
 * Write the ready-made sheet stylesheets (src/core/sheet-<name>.css) from
 * sheetCss(), for pages without a bundler: `<link rel="stylesheet"
 * href=".../@n-uf/papyrus/src/core/sheet-letter.css">`.
 *
 * Run after changing sheet.js: `pnpm --filter @n-uf/papyrus gen:sheets`.
 * A unit test fails while a file is out of date.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SHEETS, sheetCss } from "../src/core/index.js";

const coreDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "core");

/** File contents for a sheet. Shared with the staleness test. */
export function sheetCssFile(sheet) {
  return `/* Generated by scripts/gen-sheet-css.js from sheetCss(SHEETS.${sheet.name}). Do not edit. */\n${sheetCss(sheet)}`;
}

export function sheetCssPath(sheet) {
  return path.join(coreDir, `sheet-${sheet.name.toLowerCase()}.css`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  for (const sheet of Object.values(SHEETS)) {
    fs.writeFileSync(sheetCssPath(sheet), sheetCssFile(sheet));
    console.log(`wrote ${path.relative(process.cwd(), sheetCssPath(sheet))}`);
  }
}
